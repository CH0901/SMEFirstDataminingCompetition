#!/bin/zsh
# 넓은 창(25x25=50km) + 방향성 피처 수집.
# 동해안 오차의 원인인 푄·해풍은 '산맥 서쪽 구름 / 동쪽 맑음' 같은 공간
# 배치인데, 평균 하나로는 사라진다. 사분면 평균과 동서/남북 기울기가 그걸 담는다.
# 다운로드량은 기존과 같다 — 어차피 900x900 전체를 받고 창만 크게 자른다.
cd "$(dirname "$0")"
for R in "20250801 20250930" "20240801 20240930" "20230801 20230930" \
         "20260801 20260809" "20250615 20250714" "20240624 20240630"; do
  set -- ${=R}
  ./.venv/bin/python collect.py sat --start $1 --end $2 --half 12 2>&1 | grep -E "^\[sat\]" | tail -1
done
echo "=== 완료 $(date +%H:%M) ==="
