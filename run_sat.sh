#!/bin/zsh
# API 가 불안정하고 장시간 작업이 중단되기 쉬우므로 짧은 구간으로 쪼갠다.
# 이미 받은 날은 건너뛰므로 몇 번이고 다시 실행하면 된다.
cd "$(dirname "$0")"
PY=./.venv/bin/python
for R in "20260804 20260809" "20260725 20260731" "20260715 20260724" \
         "20260705 20260714" "20260625 20260704" "20260615 20260624" \
         "20260604 20260614" "20220901 20220930" "20220801 20220831"; do
  set -- ${=R}
  $PY collect.py sat --start $1 --end $2 2>&1 | grep -E "^\[sat\]|누적실패" | tail -1
  echo "  누적 $(ls data/sat_days/|wc -l|tr -d ' ')일"
done
echo "=== 완료 $(date +%H:%M) ==="
