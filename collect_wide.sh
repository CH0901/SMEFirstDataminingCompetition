#!/bin/zsh
# 넓은 창(25x25 = 50km) 재수집.
# 동해안 오차(RMSE 3.4까지)의 원인은 푄·해풍 같은 국지 현상인데, 18km 창으로는
# 태백산맥 너머의 대비가 안 잡힌다. 넓은 창과 좁은 창의 차이가 그 대비를 준다.
# 다운로드량은 같다 — 어차피 900x900 전체를 받고 창만 더 크게 자르는 것.
cd "$(dirname "$0")"
for R in "20250801 20250930" "20240801 20240930" "20230801 20230930" \
         "20250615 20250714" "20240624 20240630" "20260801 20260809"; do
  set -- ${=R}
  ./.venv/bin/python collect.py sat --start $1 --end $2 --half 12 2>&1 | grep -E "^\[sat\]" | tail -1
done
echo "=== 넓은 창 수집 완료 $(date +%H:%M) ==="
