#!/bin/zsh
# WV073(하층 수증기) + IR133(CO2) 수집.
# 습도가 지표의 34% 인데 진짜 수증기 채널을 한 번도 안 써봤다. 분리대기창
# 차분이 수증기를 간접 보정할 뿐이다. IR133 은 CO2 흡수대라 대기 온도
# 프로파일 정보를 담아 기온 쪽에 기여할 여지가 있다.
cd "$(dirname "$0")"
for R in "20250801 20250930" "20240801 20240930" "20230801 20230930" \
         "20260801 20260809" "20250615 20250714" "20240624 20240630"; do
  set -- ${=R}
  ./.venv/bin/python collect.py sat --start $1 --end $2 --channels WV073,IR133 2>&1 | grep -E "^\[sat\]" | tail -1
done
echo "=== WV/IR133 수집 완료 $(date +%H:%M) ==="
